-- Admin-only permanent product deletion.
drop function if exists public.admin_delete_product(bigint);
create or replace function public.admin_delete_product(p_product_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'Admin access required';
  end if;

  if not exists (select 1 from public.products where id=p_product_id) then
    raise exception 'Product not found';
  end if;

  if exists (select 1 from public.orders where product_id=p_product_id) then
    raise exception 'This product has order history and cannot be permanently deleted.';
  end if;

  delete from public.products where id=p_product_id;
end $$;
revoke all on function public.admin_delete_product(bigint) from public;
grant execute on function public.admin_delete_product(bigint) to authenticated;
