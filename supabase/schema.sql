create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.profiles where id=auth.uid() and is_admin=true); $$;

-- Create a public profile ONLY after the user's email has been confirmed.
-- This prevents unverified/fake signups from creating rows in public.profiles.
create or replace function public.handle_confirmed_user()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  if new.email_confirmed_at is not null then
    insert into public.profiles(id,email) values(new.id,new.email)
    on conflict(id) do update set email=excluded.email;
  end if;
  return new;
end; $$;

-- Remove the old insert-only trigger if it exists.
drop trigger if exists on_auth_user_created on auth.users;
drop trigger if exists on_auth_user_confirmed on auth.users;

-- A profile is created on confirmation (UPDATE), not on initial signup (INSERT).
create trigger on_auth_user_confirmed
after update of email_confirmed_at on auth.users
for each row
when (new.email_confirmed_at is not null and old.email_confirmed_at is null)
execute function public.handle_confirmed_user();

-- Also handle Auth users that may already be confirmed when this migration runs.
insert into public.profiles(id,email)
select id,email
from auth.users
where email_confirmed_at is not null
on conflict(id) do update set email=excluded.email;

-- Clean up profiles that were created by the previous signup trigger before
-- email confirmation was required. They will be recreated automatically after confirmation.
delete from public.profiles p
where exists (select 1 from auth.users u where u.id=p.id and u.email_confirmed_at is null);

