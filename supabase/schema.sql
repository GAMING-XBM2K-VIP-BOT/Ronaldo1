drop function if exists public.update_profile(text,text);
create or replace function public.update_profile(p_full_name text, p_avatar_url text, p_mobile_number text)
returns public.profiles
language plpgsql security definer set search_path=public
as $$
declare out_profile public.profiles;
begin
  if auth.uid() is null then raise exception 'Please log in'; end if;
  update public.profiles
  set full_name=left(coalesce(p_full_name,''),120), avatar_url=p_avatar_url, mobile_number=left(coalesce(p_mobile_number,''),30)
  where id=auth.uid()
  returning * into out_profile;
  if out_profile.id is null then raise exception 'Profile not found'; end if;
  return out_profile;
end $$;

