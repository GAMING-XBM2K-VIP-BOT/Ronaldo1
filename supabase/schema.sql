-- Admin approval: balance and request status change atomically.
create or replace function public.approve_topup(p_request_id uuid)
returns json language plpgsql security definer set search_path=public as $$
declare r public.topup_requests;
begin
 if not public.is_admin() then raise exception 'Admin access required'; end if;
 select * into r from public.topup_requests where id=p_request_id for update;
 if r.id is null or r.status <> 'pending' then raise exception 'Request is not pending'; end if;
 update public.profiles set balance=balance+r.amount where id=r.user_id;
 update public.topup_requests set status='approved', reviewed_at=now() where id=r.id;
 return json_build_object('approved',true,'amount',r.amount);
end $$;

-- Purchase: locks wallet and one available key, deducts exact variant price, then returns the key.
create or replace function public.purchase_variant(p_variant_id bigint)
returns json language plpgsql security definer set search_path=public as $$
declare
 v public.product_variants;
 p public.products;
 k public.product_keys;
 b numeric;
 oid uuid;
begin
 if auth.uid() is null then raise exception 'Please log in'; end if;
 select * into v from public.product_variants where id=p_variant_id and active=true for update;
 if v.id is null then raise exception 'Duration unavailable'; end if;
 select * into p from public.products where id=v.product_id and active=true;
 if p.id is null then raise exception 'Product unavailable'; end if;
 select balance into b from public.profiles where id=auth.uid() for update;
 if b is null then raise exception 'Profile not found'; end if;
 if b < v.price then raise exception 'Insufficient balance'; end if;
 select * into k from public.product_keys where variant_id=v.id and product_id=p.id and status='available' order by id limit 1 for update skip locked;
 if k.id is null then raise exception 'This duration is currently out of stock'; end if;
 update public.profiles set balance=balance-v.price where id=auth.uid();
 update public.product_keys set status='sold', sold_at=now() where id=k.id;
 insert into public.orders(user_id,product_id,variant_id,order_duration,amount,delivered_key) values(auth.uid(),p.id,v.id,v.label,v.price,k.secret_key) returning id into oid;
 return json_build_object('success',true,'order_id',oid,'amount',v.price,'key',k.secret_key,'product',p.name,'duration',v.label);
end $$;

-- Admin-only convenience view of stock counts.
create or replace view public.admin_variant_stock as
select v.id,v.product_id,v.label,v.price,v.active,count(k.id) filter(where k.status='available')::int as available_keys
from public.product_variants v left join public.product_keys k on k.variant_id=v.id group by v.id;

-- Public catalog stock endpoint: exposes only availability counts, never key values.
-- This is a deliberately narrow SECURITY DEFINER function: no user input, fixed search_path, and no secret columns returned.
drop view if exists public.product_variant_stock;
create or replace function public.get_public_variant_stock()
returns table(variant_id bigint, available_keys integer)
language sql
stable
security definer
set search_path=public
as $$
  select v.id, count(k.id) filter(where k.status='available')::int
  from public.product_variants v
  left join public.product_keys k on k.variant_id=v.id
  where v.active=true
  group by v.id
$$;
revoke execute on function public.get_public_variant_stock() from public;
grant execute on function public.get_public_variant_stock() to anon, authenticated;

