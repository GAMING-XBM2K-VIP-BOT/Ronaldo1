-- API hardening: sensitive business operations are callable only by authenticated users.
-- Admin-only permanent user deletion. Deleting auth.users cascades to the profile and all user-owned records.
drop function if exists public.admin_delete_user(uuid);
create or replace function public.admin_delete_user(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'Admin access required';
  end if;
  if p_user_id = auth.uid() then
    raise exception 'You cannot delete your own account';
  end if;
  if exists(select 1 from public.profiles where id=p_user_id and is_admin=true) then
    raise exception 'Admin accounts cannot be deleted from this panel';
  end if;
  delete from auth.users where id=p_user_id;
  if not found then
    raise exception 'User not found';
  end if;
end;
$$;
revoke execute on function public.admin_delete_user(uuid) from anon;
revoke execute on function public.admin_delete_user(uuid) from authenticated;
grant execute on function public.admin_delete_user(uuid) to authenticated;

