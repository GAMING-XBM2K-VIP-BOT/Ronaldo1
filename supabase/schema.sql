drop function if exists public.admin_delete_variant(bigint);
create or replace function public.admin_delete_variant(p_variant_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'Admin access required';
  end if;

  if not exists (select 1 from public.product_variants where id=p_variant_id) then
    raise exception 'Duration not found';
  end if;

